"""Thin, testable wrapper around the hashcat executable."""

from __future__ import annotations

import itertools
import queue
import re
import shutil
import subprocess
import threading
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

from .models import CrackResult, ExtractedHash

_CREATE_NO_WINDOW = 0x08000000
_ANSI_RE = re.compile(r"\x1b\[[0-9;?]*[A-Za-z]")
_PROGRESS_RE = re.compile(r"Progress\.+:\s*(\d+)/(\d+)")
_RECOVERED_RE = re.compile(r"Recovered\.+:\s*(\d+)/(\d+)")
_ETA_RE = re.compile(r"\(([^()]*)\)\s*$")
_STATUS_KEYS = (
    "Status",
    "Hash.Mode",
    "Hash.Target",
    "Time.Started",
    "Time.Estimated",
    "Kernel.Feature",
    "Guess.Mask",
    "Guess.Queue",
    "Recovered",
    "Progress",
    "Restored",
    "Speed",
    "Rejected",
    "Restore.Point",
    "Restore.Sub",
    "Candidate.Engine",
    "Candidates",
)


@dataclass
class AttackConfig:
    mode: int
    hash_file: Path
    attack_mode: int  # 0 = wordlist/stdin, 3 = mask
    wordlist: Optional[Path] = None
    mask: str = ""
    workload: int = 2
    session_name: str = "archive-crack"
    # Pure brute-force mode: candidates are generated by the GUI and fed to
    # hashcat through stdin, so hashcat's mask kernel is not required.
    stdin_candidates: bool = False
    stdin_charset: str = ""
    stdin_min: int = 1
    stdin_max: int = 6

    def candidate_count(self) -> int:
        total = 0
        size = len(self.stdin_charset)
        for length in range(self.stdin_min, self.stdin_max + 1):
            total += size ** length
        return total

    def command(self, hashcat: Path, potfile: Path, outfile: Path) -> list[str]:
        args = [
            str(hashcat),
            "-m",
            str(self.mode),
            "-a",
            str(self.attack_mode),
            str(self.hash_file),
        ]
        if self.stdin_candidates:
            # hashcat switches to stdin when -a 0 has no wordlist argument.
            count = self.candidate_count()
            if 0 < count <= 10**18:
                args.extend(["--stdin-count", str(count)])
        elif self.attack_mode == 0:
            if not self.wordlist:
                raise ValueError("字典攻击缺少字典文件。")
            args.append(str(self.wordlist))
        else:
            if not self.mask.strip():
                raise ValueError("掩码攻击缺少掩码表达式。")
            args.append(self.mask.strip())
        args.extend(
            [
                # The GUI keeps its own result history.  A shared potfile made
                # hashcat silently skip an already-cracked hash without writing
                # to --outfile, which looked like "not found" in the UI.
                "--potfile-disable",
                "--outfile",
                str(outfile),
                "--outfile-format",
                "2",
                "--status",
                "--status-timer",
                "1",
                "--session",
                self.session_name,
                "--restore-disable",
                "--logfile-disable",
                "-w",
                str(self.workload),
            ]
        )
        return args


@dataclass
class StatusSnapshot:
    status: str = ""
    progress: float = 0.0
    tried: int = 0
    total: int = 0
    speed: str = ""
    eta: str = ""
    recovered: int = 0
    recovered_total: int = 0
    mask: str = ""
    mode: str = ""


def _clean_line(line: str) -> str:
    line = _ANSI_RE.sub("", line)
    line = line.replace("\x08", "")
    return line.strip()


def _looks_like_status(line: str) -> bool:
    return any(line.startswith(key + ".") or line == key for key in _STATUS_KEYS)


def _value(line: str) -> str:
    if ":" not in line:
        return ""
    return line.split(":", 1)[1].strip()


class HashcatRunner:
    """Runs one attack in a background thread and reports progress via a queue."""

    def __init__(
        self,
        hashcat_dir: Path,
        events: queue.Queue,
        config: AttackConfig,
        potfile: Path,
        outfile: Path,
    ) -> None:
        self.hashcat_dir = Path(hashcat_dir)
        self.hashcat = self.hashcat_dir / "hashcat.exe"
        self.events = events
        self.config = config
        self.potfile = Path(potfile)
        self.outfile = Path(outfile)
        self._process: subprocess.Popen | None = None
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None
        self._last_progress_log = 0.0

    # -- public API -----------------------------------------------------
    @property
    def is_running(self) -> bool:
        return bool(self._thread and self._thread.is_alive())

    def start(self) -> None:
        if self._thread and self._thread.is_alive():
            raise RuntimeError("已有破解任务正在运行。")
        self._stop.clear()
        self._thread = threading.Thread(target=self._run_safely, daemon=True)
        self._thread.start()

    def stop(self) -> None:
        self._stop.set()
        proc = self._process
        if proc and proc.poll() is None:
            try:
                proc.terminate()
            except OSError:
                pass

    def join(self, timeout: float | None = None) -> None:
        if self._thread:
            self._thread.join(timeout)

    # -- internals ------------------------------------------------------
    def _emit(self, kind: str, payload=None) -> None:
        self.events.put((kind, payload))

    def _run_safely(self) -> None:
        started = time.time()
        try:
            result = self._run()
        except Exception as exc:  # keep the UI alive on unexpected failures
            result = CrackResult(
                found=False,
                exit_code=-1,
                message=f"运行失败：{exc}",
                elapsed=time.time() - started,
            )
        if self._stop.is_set() and not result.found:
            result = CrackResult(
                found=False,
                exit_code=2,
                message="已停止破解。",
                elapsed=time.time() - started,
                tried=result.tried,
                total=result.total,
            )
        self._emit("done", result)

    def _run(self) -> CrackResult:
        if not self.hashcat.exists():
            return CrackResult(
                found=False,
                exit_code=-1,
                message=f"找不到 hashcat：{self.hashcat}",
            )
        if not self.config.hash_file.exists():
            return CrackResult(
                found=False,
                exit_code=-1,
                message="哈希文件不存在。",
            )

        started = time.time()
        self.outfile.parent.mkdir(parents=True, exist_ok=True)
        self.potfile.parent.mkdir(parents=True, exist_ok=True)

        try:
            self.outfile.unlink(missing_ok=True)
        except OSError:
            pass

        cmd = self.config.command(self.hashcat, self.potfile, self.outfile)
        self._emit("command", cmd)
        self._emit("log", f"启动 hashcat（模式 {self.config.mode}）")

        last_code, last_output = self._run_process(cmd, started)
        password = self._read_outfile()
        if password:
            result = CrackResult(
                found=True,
                password=password,
                exit_code=last_code,
                message="已找到密码。",
                elapsed=time.time() - started,
            )
            self._emit("found", password)
            return result

        if self._stop.is_set():
            return CrackResult(
                found=False,
                exit_code=2,
                message="已停止破解。",
                elapsed=time.time() - started,
            )

        password = self._read_outfile()
        if password:
            self._emit("found", password)
            return CrackResult(
                found=True,
                password=password,
                exit_code=last_code,
                message="已找到密码。",
                elapsed=time.time() - started,
            )

        message = self._message_for_exit(last_code, last_output)
        return CrackResult(
            found=False,
            exit_code=last_code,
            message=message,
            elapsed=time.time() - started,
        )

    def _run_process(self, cmd: list[str], started: float) -> tuple[int, str]:
        self._emit("log", "命令：" + _format_command(cmd))
        proc = subprocess.Popen(
            cmd,
            cwd=str(self.hashcat_dir),
            stdin=subprocess.PIPE if self.config.stdin_candidates else subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            bufsize=0,
            creationflags=_CREATE_NO_WINDOW,
        )
        self._process = proc
        assert proc.stdout is not None

        if self.config.stdin_candidates and proc.stdin is not None:
            threading.Thread(
                target=self._feed_stdin,
                args=(proc, proc.stdin),
                daemon=True,
            ).start()

        buffer = ""
        output_parts: list[str] = []
        status = StatusSnapshot()
        recent_non_status: list[str] = []

        while True:
            chunk = proc.stdout.read(4096)
            if not chunk:
                break
            text = chunk.decode("utf-8", "replace")
            output_parts.append(text)
            buffer += text
            # hashcat separates status frames with CR, ordinary lines with LF.
            parts = re.split(r"[\r\n]", buffer)
            buffer = parts.pop()
            for raw in parts:
                line = _clean_line(raw)
                if not line:
                    continue
                if _looks_like_status(line):
                    self._apply_status(status, line)
                    self._emit("status", status)
                    continue
                if line.startswith("[s]tatus") or "Status..........." in line:
                    continue
                if line not in recent_non_status:
                    recent_non_status.append(line)
                    if len(recent_non_status) > 200:
                        recent_non_status.pop(0)
                    if self._should_log(line):
                        self._emit("log", line)
            if self._stop.is_set():
                if proc.poll() is None:
                    try:
                        proc.terminate()
                    except OSError:
                        pass
                break

        if buffer.strip():
            line = _clean_line(buffer)
            if line and self._should_log(line):
                self._emit("log", line)

        for stream in (proc.stdout,):
            try:
                stream.close()
            except Exception:
                pass
        try:
            code = proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()
            code = proc.wait()
        self._process = None
        # Windows reports negative exit codes as unsigned DWORDs.
        code = int(code)
        if code > 0x7FFFFFFF:
            code -= 0x100000000
        return code, "".join(output_parts)

    @staticmethod
    def _write_all(stream, data: bytes | bytearray) -> None:
        view = memoryview(data)
        while view:
            written = stream.write(view)
            if not written:
                raise BrokenPipeError
            view = view[written:]

    def _feed_stdin(self, proc: subprocess.Popen, stream) -> None:
        """Generate pure brute-force candidates and write them to hashcat."""
        charset = self.config.stdin_charset
        if not charset:
            try:
                stream.close()
            except OSError:
                pass
            return

        buffer = bytearray()
        try:
            for length in range(self.config.stdin_min, self.config.stdin_max + 1):
                for parts in itertools.product(charset, repeat=length):
                    if self._stop.is_set() or proc.poll() is not None:
                        return
                    buffer.extend("".join(parts).encode("utf-8"))
                    buffer.append(0x0A)
                    if len(buffer) >= 64 * 1024:
                        self._write_all(stream, buffer)
                        buffer.clear()
            if buffer:
                self._write_all(stream, buffer)
        except (BrokenPipeError, OSError):
            pass
        finally:
            try:
                stream.close()
            except OSError:
                pass

    def _apply_status(self, status: StatusSnapshot, line: str) -> None:
        value = _value(line)
        if line.startswith("Status."):
            status.status = value
        elif line.startswith("Hash.Mode."):
            status.mode = value
        elif line.startswith("Speed."):
            status.speed = value
        elif line.startswith("Guess.Mask."):
            status.mask = value
        elif line.startswith("Progress."):
            match = _PROGRESS_RE.search(line)
            if match:
                status.tried = int(match.group(1))
                status.total = int(match.group(2))
                if status.total:
                    status.progress = min(100.0, status.tried * 100.0 / status.total)
        elif line.startswith("Recovered."):
            match = _RECOVERED_RE.search(line)
            if match:
                status.recovered = int(match.group(1))
                status.recovered_total = int(match.group(2))
        elif line.startswith("Time.Estimated."):
            match = _ETA_RE.search(value)
            status.eta = match.group(1) if match else value

    def _should_log(self, line: str) -> bool:
        ignored = (
            "Session..........:",
            "Status...........:",
            "Hash.Target",
            "Time.Started",
            "Time.Estimated",
            "Kernel.Feature",
            "Guess.Queue",
            "Recovered........:",
            "Progress.........:",
            "Rejected.........:",
            "Restore.Point",
            "Restore.Sub",
            "Candidate.Engine",
            "Candidates.#",
            "Bitmaps:",
            "Optimizers applied:",
            "Watchdog:",
        )
        if line.startswith(ignored):
            return False
        if "Please be patient" in line or line.startswith("Initializing"):
            return False
        return True

    def _read_outfile(self) -> str:
        try:
            if not self.outfile.exists():
                return ""
            text = self.outfile.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return ""
        for line in reversed(text.splitlines()):
            password = line.rstrip("\r\n")
            if password:
                return password
        return ""

    @staticmethod
    def _message_for_exit(code: int, output: str) -> str:
        lowered = output.lower()
        if "self-test failed" in lowered or "self-test failure" in lowered:
            return (
                "显卡内核对当前攻击模式自检失败，hashcat 已中止。"
                "请更新显卡驱动，或改用字典攻击。"
            )
        if "no such file or directory" in lowered:
            return "hashcat 找不到字典或哈希文件，请重新选择文件。"
        if "no opencl devices found" in lowered or "no devices found" in lowered:
            return "没有找到可用的 OpenCL 设备，请更新显卡驱动后重试。"
        if "not enough memory" in lowered or "out of memory" in lowered:
            return "显存不足，请关闭其他程序或改用更小的字典/掩码。"
        if "token length exception" in lowered or "hashfile" in lowered and "exception" in lowered:
            return "哈希文件格式不被 hashcat 接受，请确认压缩包未损坏。"
        if code == 0:
            return "任务结束，但未读取到密码。可能该哈希已在 potfile 中，请查看日志。"
        if code == 1:
            return "已尝试完所有候选密码，没有找到正确密码。"
        if code == 2:
            return "hashcat 被中止。"
        if code == 3:
            return "hashcat 已保存进度并退出。"
        if code == 4:
            return "hashcat 运行出错，请查看下方日志。"
        return f"hashcat 退出码 {code}，请查看日志。"


def _format_command(cmd: list[str]) -> str:
    parts = []
    for item in cmd:
        if " " in item or "\\" in item:
            parts.append(f'"{item}"')
        else:
            parts.append(item)
    return " ".join(parts)


def find_hashcat(preferred: str | Path | None = None) -> Optional[Path]:
    """Locate hashcat.exe in a few sensible places."""
    candidates: list[Path] = []
    if preferred:
        p = Path(preferred)
        candidates.append(p / "hashcat.exe" if p.is_dir() else p)
    here = Path(__file__).resolve().parent.parent
    candidates.extend(
        [
            here / "runtime" / "hashcat" / "hashcat.exe",
            here / "hashcat" / "hashcat.exe",
            Path(r"D:\edge浏览器下载文件\hashcat-8.0.0\hashcat.exe"),
            Path(r"C:\hashcat\hashcat.exe"),
        ]
    )
    for candidate in candidates:
        if candidate.exists():
            return candidate
    found = shutil.which("hashcat")
    return Path(found) if found else None


def hashcat_version(hashcat: Path) -> str:
    try:
        proc = subprocess.run(
            [str(hashcat), "--version"],
            cwd=str(hashcat.parent),
            capture_output=True,
            text=True,
            errors="replace",
            timeout=15,
            creationflags=_CREATE_NO_WINDOW,
        )
        text = (proc.stdout or proc.stderr).strip()
        for line in text.splitlines():
            if line.strip().startswith("v"):
                return line.strip()
    except Exception:
        pass
    return "未知"
